/**
 * Generates the font the evidence marks are set in, and prints it as the base64 constant that
 * `src/render/mark-font.ts` carries.
 *
 * WHY THIS EXISTS, measured rather than assumed:
 *
 * The marks are text. Text in a document gets its glyphs from a font, and Chrome embeds a SUBSET
 * of that font into the PDF it produces — only the glyphs actually used. If the marks are set in
 * the same font as the document's own prose, the marks' characters ENLARGE that subset. The
 * marked PDF then carries a different font program from the baseline: measured on the neutral
 * fixture, 17 584 bytes against 15 508, different hash, same font name.
 *
 * A different font program is rasterised differently. pdfjs installs the embedded font through
 * the browser's own text machinery, so FreeType hints the two subsets slightly differently and
 * thousands of edge pixels change — 1116 on the x86_64 CI runner, 1121 in an arm64 container.
 * poppler, which brings its own rasteriser, reports 0 on the same pair of files. The pixels were
 * never in the document; they are the footprint of the measuring apparatus, and the overlay check
 * was reading its own shadow as contamination and withholding the evidence.
 *
 * The fix is that the marks may not share a font with anything. This font has a family name no
 * document will collide with and exactly the seventeen characters a token can contain.
 *
 * The glyphs are plain rectangles, and the first attempt got this wrong in a way worth writing
 * down. Empty outlines looked strictly better: the marks are `color: transparent`, so their
 * invisibility rests on a colour a hostile stylesheet might try to reach, while a glyph with no
 * contours has nothing to paint in any colour. Measured against the real renderer, that font
 * never reached the PDF at all — Chrome emits no drawing operation for glyphs with nothing to
 * draw, so the tokens vanished from the text stream and not one mark was refound. The raster
 * comparison went to 0 and the binding went to nothing, which from the outside looks like
 * success. Invisibility here comes from the colour, as it always did; this font's job is only to
 * keep the marks out of the document's font subset.
 *
 * The advance width is deliberately NOT zero. A zero advance stacks every character of a token on
 * one point, and the PDF text extractor then reports one item where the mark's position should
 * be. The marks are found by matching extracted text against the token, so they must remain
 * separable. 1000 units at 1px font-size is one pixel per character, inside the box the readback
 * already allows.
 *
 * Run: node tools/make-mark-font.mjs        (writes src/render/mark-font.ts)
 *      node tools/make-mark-font.mjs --check (exits non-zero if the file is out of date)
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const TARGET = join(HERE, "..", "src", "render", "mark-font.ts");

/** Every character `installOverlay` can put in a token: "BLSID" + three digits + "A" or "E". */
const CHARS = [..."BLSIDAE0123456789"];
const FAMILY = "breaklint-mark";
const UPM = 1000;

const PY = `
import base64, io, sys
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

chars = ${JSON.stringify(CHARS)}
upm = ${UPM}
names = {c: ("uni%04X" % ord(c)) for c in chars}
order = [".notdef"] + [names[c] for c in chars]

fb = FontBuilder(upm, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap({ord(c): names[c] for c in chars})

# One rectangle per glyph. The shape is irrelevant — it is drawn in a transparent colour and
# never seen — but it must EXIST, or Chrome emits no text operation and the mark is unfindable.
def box():
    pen = TTGlyphPen(None)
    pen.moveTo((80, 0)); pen.lineTo((80, 700)); pen.lineTo((920, 700)); pen.lineTo((920, 0))
    pen.closePath()
    return pen.glyph()

fb.setupGlyf({g: box() for g in order})
fb.setupHorizontalMetrics({g: (upm, 0) for g in order})
fb.setupHorizontalHeader(ascent=upm, descent=0)
fb.setupNameTable({
    "familyName": "${FAMILY}",
    "styleName": "Regular",
    "psName": "breaklintmark",
    # A font that travels inside a PDF should say what it is when someone opens the file.
    "manufacturer": "generated by tools/make-mark-font.mjs in the breaklint repository",
    "description": "Carries the position of an evidence mark. Drawn in a transparent colour and never seen.",
})
fb.setupOS2(sTypoAscender=upm, usWinAscent=upm, usWinDescent=0, achVendID="BRKL")
fb.setupPost(isFixedPitch=1)
# A fixed creation date keeps the output byte-identical across runs; a timestamp would make every
# regeneration look like a change.
fb.updateHead(created=0, modified=0)
buf = io.BytesIO()
fb.save(buf)
sys.stdout.write(base64.b64encode(buf.getvalue()).decode("ascii"))
`;

const base64 = execFileSync("python3", ["-c", PY], { encoding: "utf8" }).trim();

const file = `/**
 * GENERATED by \`tools/make-mark-font.mjs\` — do not edit by hand. CI runs the generator with
 * \`--check\` and fails if this file is not what it produces; \`tests/unit/mark-font.test.ts\`
 * additionally parses the shipped binary, so a hand-edit is caught even where fontTools is absent.
 *
 * The font the evidence marks are set in: ${CHARS.length} characters, one rectangle each. It
 * exists so that the marks can never enlarge the font subset of the document's own text, because
 * a larger subset is a different font program and a different font program rasterises
 * differently. The full measurement, including why the glyphs are not empty, is in the
 * generator's header.
 */

/** Family name of the mark font. Deliberately unlike anything a document would name. */
export const MARK_FONT_FAMILY = "${FAMILY}";

/** The characters the font covers — every character a mark token can contain. */
export const MARK_FONT_CHARS = ${JSON.stringify(CHARS.join(""))};

/** The font itself, base64-encoded TrueType, ${Math.round(((base64.length * 3) / 4 / 1024) * 10) / 10} kB decoded. */
export const MARK_FONT_BASE64 =
  "${base64}";

/**
 * The \`src\` descriptor, for \`new FontFace(MARK_FONT_FAMILY, MARK_FONT_SRC)\`.
 *
 * Deliberately not a \`@font-face\` rule in a \`<style>\` element: that would be a new node in an
 * already-measured document, which this product's own tamper detection catches — and did.
 */
export const MARK_FONT_SRC = \`url(data:font/ttf;base64,\${MARK_FONT_BASE64}) format("truetype")\`;
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(TARGET, "utf8");
  if (current !== file) {
    console.error("src/render/mark-font.ts is not what the generator produces. Run: node tools/make-mark-font.mjs");
    process.exit(1);
  }
  console.log("mark font: generated file matches the generator");
} else {
  writeFileSync(TARGET, file);
  console.log(`wrote ${TARGET} — ${CHARS.length} chars, ${Math.round((base64.length * 3) / 4)} bytes of font`);
}
